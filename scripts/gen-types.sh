#!/usr/bin/env bash
# Regenerate the TypeScript bindings in web/src/api/types from the Rust DTOs
# (ob-core, `ts` feature, via ts-rs). Output dir and number handling come from
# .cargo/config.toml (TS_RS_EXPORT_DIR, TS_RS_LARGE_INT).
#
#   scripts/gen-types.sh          regenerate files in place
#   scripts/gen-types.sh --check  regenerate and fail if the files on disk differ from the
#                                 fresh output (CI and scripts/check.sh); leaves them untouched
#
# Hand-maintained files in that directory (overrides.ts) are never deleted.
set -euo pipefail
cd "$(dirname "$0")/.."
export LC_ALL=C

OUT=web/src/api/types
mkdir -p "$OUT"

# --check compares the files on disk (committed or not) with a fresh generation, so it passes
# for regenerated-but-uncommitted bindings and fails for stale ones.
if [[ "${1:-}" == "--check" ]]; then
  SNAPSHOT="$(mktemp -d)"
  trap 'rm -rf "$SNAPSHOT"' EXIT
  cp -R "$OUT/." "$SNAPSHOT/"
fi

# Drop previously generated files so renamed/removed Rust types do not linger.
find "$OUT" -name '*.ts' -exec grep -l 'generated by \[ts-rs\]' {} + 2>/dev/null |
  while read -r f; do rm -f "$f"; done
rm -f "$OUT/index.ts"
find "$OUT" -mindepth 1 -type d -empty -delete 2>/dev/null || true
mkdir -p "$OUT"

cargo test -p ob-core --features ts export_bindings

# Barrel file: one `export type` per generated type plus the hand-written overrides.
{
  echo "// Barrel for the generated bindings. Regenerated by scripts/gen-types.sh; do not edit."
  for f in $(cd "$OUT" && find . -maxdepth 1 -name '*.ts' ! -name index.ts ! -name overrides.ts | sed 's|^\./||; s|\.ts$||' | sort); do
    echo "export type { $f } from \"./$f\";"
  done
  echo "export type { JsonValue } from \"./serde_json/JsonValue\";"
  echo "export type * from \"./overrides\";"
} >"$OUT/index.ts"

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -r "$SNAPSHOT" "$OUT" >/dev/null; then
    echo "TypeScript bindings are out of date. Run scripts/gen-types.sh and commit the result." >&2
    diff -rq "$SNAPSHOT" "$OUT" >&2 || true
    # Put the original files back: --check never modifies the tree.
    rm -rf "$OUT"
    mkdir -p "$OUT"
    cp -R "$SNAPSHOT/." "$OUT/"
    exit 1
  fi
  echo "TypeScript bindings are current."
fi
