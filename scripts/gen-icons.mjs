// Generates crates/server/data/lucide-icons.txt, the list of Lucide icon names the server
// accepts from AI agents (MCP) and searches for `list_icons`. Run through scripts/gen-icons.sh.
//
// Source of truth is the installed `lucide-react` package in web/node_modules (the same one the
// web picker draws from), so the server list and the picker cannot drift apart: each canonical
// icon module exports `__iconData: { name, aliases? }`.
//
// Output, one icon per line, sorted: the canonical kebab-case name, then its aliases (old names
// that still draw) separated by spaces.
import { readdir } from "node:fs/promises";
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const lucide = path.join(root, "web", "node_modules", "lucide-react");
const iconsDir = path.join(lucide, "dist", "esm", "icons");

let version;
try {
  version = JSON.parse(readFileSync(path.join(lucide, "package.json"), "utf8")).version;
} catch {
  console.error("lucide-react is not installed: run `npm ci --ignore-scripts` in web/ first.");
  process.exit(2);
}

const entries = new Map();
for (const file of (await readdir(iconsDir)).filter((f) => f.endsWith(".mjs")).sort()) {
  const mod = await import(pathToFileURL(path.join(iconsDir, file)).href);
  const data = mod.__iconData;
  if (!data) continue; // an alias file re-exporting another icon
  const aliases = [...(data.aliases ?? [])].sort();
  entries.set(data.name, aliases);
}

const valid = /^[a-z0-9-]{1,64}$/;
const lines = [];
for (const name of [...entries.keys()].sort()) {
  const aliases = entries.get(name).filter((a) => a !== name && !entries.has(a));
  for (const n of [name, ...aliases]) {
    if (!valid.test(n)) throw new Error(`unexpected icon name ${JSON.stringify(n)}`);
  }
  lines.push([name, ...aliases].join(" "));
}
if (lines.length < 1500) throw new Error(`only ${lines.length} icons found: did lucide-react change its layout?`);

process.stdout.write(
  `# Lucide icon names (lucide-react ${version}), generated by scripts/gen-icons.sh. Do not edit.\n` +
    `# One icon per line: the canonical kebab-case name, then its aliases (old names that still draw).\n` +
    lines.join("\n") +
    "\n",
);
