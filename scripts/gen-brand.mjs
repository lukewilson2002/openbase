// Builds the web client's brand files from brand/ (the source of truth for the logo).
// Run through scripts/gen-brand.sh. Writes, relative to the repository root:
//
//   web/public/favicon.svg             small mark (16-32 px variant), the browser tab icon
//   web/public/favicon.ico             16/32/48 px fallback
//   web/public/apple-touch-icon.png    180 px, full-bleed white
//   web/public/icon-192.png            web app manifest icons (see web/public/manifest.webmanifest)
//   web/public/icon-512.png
//   web/public/icon-maskable-512.png
//   web/src/components/brandMarks.ts   the mark, the small mark and the lockup as path data, so
//                                      <Logo> draws them inline (themeable wordmark, no request)
//
// With --check nothing is written; the script exits 1 when a committed file differs.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const check = process.argv.includes("--check");

const read = (rel) => readFileSync(path.join(root, rel));
const text = (rel) => read(rel).toString("utf8");

const outputs = new Map(); // repo-relative path -> Buffer | string

const copies = [
  ["brand/openbase-mark-small.svg", "web/public/favicon.svg"],
  ["brand/favicon.ico", "web/public/favicon.ico"],
  ["brand/png/apple-touch-icon.png", "web/public/apple-touch-icon.png"],
  ["brand/png/icon-192.png", "web/public/icon-192.png"],
  ["brand/png/icon-512.png", "web/public/icon-512.png"],
  ["brand/png/icon-maskable-512.png", "web/public/icon-maskable-512.png"],
];
for (const [from, to] of copies) outputs.set(to, read(from));

/** [{ fill, d }] for every <path> of an SVG, in document order. */
function paths(svg) {
  const found = [...svg.matchAll(/<path\b([^>]*?)\/>/g)].map((m) => {
    const fill = /fill="([^"]+)"/.exec(m[1])?.[1];
    const d = / d="([^"]+)"/.exec(m[1])?.[1];
    if (!fill || !d) throw new Error(`unexpected <path> in a brand SVG: ${m[0].slice(0, 80)}`);
    return { fill, d };
  });
  if (found.length === 0) throw new Error("no paths found in a brand SVG");
  return found;
}
const viewBox = (svg) => /viewBox="([^"]+)"/.exec(svg)?.[1] ?? (() => { throw new Error("no viewBox"); })();

const mark = text("brand/openbase-mark.svg");
const small = text("brand/openbase-mark-small.svg");
const lockup = text("brand/openbase-lockup.svg");
const lockupPaths = paths(lockup);
// The wordmark is the last path; it is the only one that is not part of the cube.
const wordmark = lockupPaths[lockupPaths.length - 1];
if (wordmark.fill.toUpperCase() !== "#0B1220") throw new Error("expected the last lockup path to be the ink wordmark");

const lit = (list) => "[\n" + list.map((p) => `  [${JSON.stringify(p.fill)}, ${JSON.stringify(p.d)}],`).join("\n") + "\n] as const";
outputs.set(
  "web/src/components/brandMarks.ts",
  `// Generated by scripts/gen-brand.sh from brand/*.svg. Do not edit.
// [fill, path data] pairs, drawn by components/Logo.tsx.

/** The master mark (24 px and up). */
export const MARK_VIEW_BOX = ${JSON.stringify(viewBox(mark))};
export const MARK_PATHS = ${lit(paths(mark))};

/** The small mark: wider gaps, no sliver; for 16-32 px. */
export const MARK_SMALL_VIEW_BOX = ${JSON.stringify(viewBox(small))};
export const MARK_SMALL_PATHS = ${lit(paths(small))};

/** The lockup: the mark and the outlined wordmark. The wordmark is drawn in currentColor. */
export const LOCKUP_VIEW_BOX = ${JSON.stringify(viewBox(lockup))};
export const LOCKUP_MARK_PATHS = ${lit(lockupPaths.slice(0, -1))};
export const LOCKUP_WORDMARK_PATH = ${JSON.stringify(wordmark.d)};
`,
);

let stale = 0;
for (const [rel, content] of outputs) {
  const file = path.join(root, rel);
  const fresh = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (check) {
    if (!existsSync(file) || !readFileSync(file).equals(fresh)) {
      console.error(`${rel} is out of date.`);
      stale++;
    }
  } else {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, fresh);
  }
}
if (check) {
  if (stale) {
    console.error("Run scripts/gen-brand.sh and commit the result.");
    process.exit(1);
  }
  console.log("Brand files are current.");
} else {
  console.log(`Wrote ${outputs.size} files from brand/.`);
}
