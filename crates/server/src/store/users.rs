/// Stored as `password_hash` for accounts created without a password (they
/// set one through a reset link). Never verifies: it is not a PHC string.
pub const UNUSABLE_PASSWORD_HASH: &str = "!";

/// Maximum length of a display name, in characters.
pub const MAX_NAME_LEN: usize = 100;

/// Reset links sent by email are valid for 1 hour.
pub const RESET_TTL_MS: i64 = 3600 * 1000;
/// Reset links generated by an admin (handed over out of band) last 24 hours.
pub const ADMIN_RESET_TTL_MS: i64 = 24 * 3600 * 1000;

/// Trim and lightly validate an email address. Uniqueness is case-insensitive
/// (the column is COLLATE NOCASE).
pub fn normalize_email(email: &str) -> AppResult<String> {
    let e = email.trim();
    let valid = e.len() <= 254
        && e.split_once('@').is_some_and(|(local, domain)| {
            !local.is_empty()
                && domain.contains('.')
                && !domain.starts_with('.')
                && !domain.ends_with('.')
        })
        && !e.chars().any(|c| c.is_whitespace() || c.is_control());
    if !valid {
        return Err(AppError::bad_request("invalid email address"));
    }
    Ok(e.to_string())
}

/// Trim and validate a display name.
pub fn validate_name(name: &str) -> AppResult<String> {
    let n = name.trim();
    if n.is_empty() {
        return Err(AppError::bad_request("name is required"));
    }
    if n.chars().count() > MAX_NAME_LEN {
        return Err(AppError::bad_request(format!(
            "name must be at most {MAX_NAME_LEN} characters"
        )));
    }
    if n.chars().any(char::is_control) {
        return Err(AppError::bad_request("name contains invalid characters"));
    }
    Ok(n.to_string())
}

/// Validate an IANA timezone name; empty means "unset" (None).
pub fn validate_timezone(tz: &str) -> AppResult<Option<String>> {
    let tz = tz.trim();
    if tz.is_empty() {
        return Ok(None);
    }
    tz.parse::<chrono_tz::Tz>()
        .map_err(|_| AppError::bad_request(format!("unknown timezone '{tz}'")))?;
    Ok(Some(tz.to_string()))
}

/// A full `users` row.
#[derive(Debug, Clone)]
pub struct UserRow {
    pub id: String,
    pub email: String,
    pub name: String,
    pub password_hash: String,
    pub is_admin: bool,
    pub is_active: bool,
    pub timezone: Option<String>,
    pub totp_secret: Option<String>,
    pub totp_enabled: bool,
    pub created_at: i64,
    pub last_login_at: Option<i64>,
}

const COLUMNS: &str = "id, email, name, password_hash, is_admin, is_active, timezone, \
                       totp_secret, totp_enabled, created_at, last_login_at";

impl UserRow {
    fn from_row(r: &Row) -> rusqlite::Result<UserRow> {
        Ok(UserRow {
            id: r.get(0)?,
            email: r.get(1)?,
            name: r.get(2)?,
            password_hash: r.get(3)?,
            is_admin: r.get(4)?,
            is_active: r.get(5)?,
            timezone: r.get(6)?,
            totp_secret: r.get(7)?,
            totp_enabled: r.get(8)?,
            created_at: r.get(9)?,
            last_login_at: r.get(10)?,
        })
    }

    pub fn to_api(&self) -> User {
        User {
            id: self.id.clone(),
            email: self.email.clone(),
            name: self.name.clone(),
            is_admin: self.is_admin,
            timezone: self.timezone.clone(),
            totp_enabled: self.totp_enabled,
        }
    }

    /// The admin view of the user, with a passkey count of 0: callers that show it to an
    /// administrator fill the real count in ([`admin_view`]).
    pub fn to_admin(&self) -> AdminUser {
        AdminUser {
            id: self.id.clone(),
            email: self.email.clone(),
            name: self.name.clone(),
            is_admin: self.is_admin,
            is_active: self.is_active,
            totp_enabled: self.totp_enabled,
            passkey_count: 0,
            created_at: self.created_at,
            last_login_at: self.last_login_at,
        }
    }
}

/// [`UserRow::to_admin`] with the user's real passkey count.
pub fn admin_view(conn: &Connection, user: &UserRow) -> AppResult<AdminUser> {
    let mut view = user.to_admin();
    view.passkey_count = crate::store::passkeys::count(conn, &user.id)?;
    Ok(view)
}

pub fn get(conn: &Connection, id: &str) -> AppResult<Option<UserRow>> {
    Ok(conn
        .query_row(
            &format!("SELECT {COLUMNS} FROM users WHERE id = ?1"),
            [id],
            UserRow::from_row,
        )
        .optional()?)
}

/// Like [`get`] but 404 when missing.
pub fn require(conn: &Connection, id: &str) -> AppResult<UserRow> {
    get(conn, id)?.ok_or_else(|| AppError::not_found("user"))
}

/// Look up by email (case-insensitive).
pub fn get_by_email(conn: &Connection, email: &str) -> AppResult<Option<UserRow>> {
    Ok(conn
        .query_row(
            &format!("SELECT {COLUMNS} FROM users WHERE email = ?1"),
            [email.trim()],
            UserRow::from_row,
        )
        .optional()?)
}

pub fn count(conn: &Connection) -> AppResult<i64> {
    Ok(conn.query_row("SELECT count(*) FROM users", [], |r| r.get(0))?)
}

/// Insert a user. `email` and `name` must already be validated.
/// Errors with 409 if the email is taken.
pub fn create(
    conn: &Connection,
    email: &str,
    name: &str,
    password_hash: &str,
    is_admin: bool,
) -> AppResult<String> {
    let id = new_id(ob_core::ids::USER);
    let now = now_ms();
    conn.execute(
        "INSERT INTO users (id, email, name, password_hash, is_admin, created_at, updated_at)
         VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?6)",
        params![id, email, name, password_hash, is_admin, now],
    )
    .map_err(|e| match e {
        rusqlite::Error::SqliteFailure(f, _)
            if f.code == rusqlite::ErrorCode::ConstraintViolation =>
        {
            AppError::conflict("an account with that email already exists")
        }
        other => other.into(),
    })?;
    Ok(id)
}

/// Update name and/or timezone (`Some(None)` clears the timezone).
pub fn update_profile(
    conn: &Connection,
    id: &str,
    name: Option<&str>,
    timezone: Option<Option<&str>>,
) -> AppResult<()> {
    let now = now_ms();
    if let Some(name) = name {
        conn.execute(
            "UPDATE users SET name = ?1, updated_at = ?2 WHERE id = ?3",
            params![name, now, id],
        )?;
    }
    if let Some(tz) = timezone {
        conn.execute(
            "UPDATE users SET timezone = ?1, updated_at = ?2 WHERE id = ?3",
            params![tz, now, id],
        )?;
    }
    Ok(())
}

pub fn set_password_hash(conn: &Connection, id: &str, hash: &str) -> AppResult<()> {
    conn.execute(
        "UPDATE users SET password_hash = ?1, updated_at = ?2 WHERE id = ?3",
        params![hash, now_ms(), id],
    )?;
    Ok(())
}

pub fn touch_last_login(conn: &Connection, id: &str) -> AppResult<()> {
    conn.execute(
        "UPDATE users SET last_login_at = ?1 WHERE id = ?2",
        params![now_ms(), id],
    )?;
    Ok(())
}

/// Store a TOTP secret and whether 2FA is enabled. `None` clears the secret
/// (and the replay marker).
pub fn set_totp(conn: &Connection, id: &str, secret: Option<&str>, enabled: bool) -> AppResult<()> {
    conn.execute(
        "UPDATE users SET totp_secret = ?1, totp_enabled = ?2, updated_at = ?3 WHERE id = ?4",
        params![secret, enabled, now_ms(), id],
    )?;
    if secret.is_none() {
        totp::clear_replay_state(conn, id)?;
    }
    Ok(())
}

/// Every user, oldest first, for the admin screen.
pub fn list_admin(conn: &Connection) -> AppResult<Vec<AdminUser>> {
    let mut stmt = conn.prepare(&format!(
        "SELECT {COLUMNS} FROM users ORDER BY created_at, id"
    ))?;
    let rows = stmt.query_map([], UserRow::from_row)?;
    let users = rows.collect::<Result<Vec<_>, _>>()?;
    users.iter().map(|u| admin_view(conn, u)).collect()
}

fn other_active_admins(conn: &Connection, except_id: &str) -> AppResult<i64> {
    Ok(conn.query_row(
        "SELECT count(*) FROM users WHERE is_admin = 1 AND is_active = 1 AND id != ?1",
        [except_id],
        |r| r.get(0),
    )?)
}

/// Apply an admin's change to a user, enforcing the safety rules:
/// admins cannot deactivate or demote themselves, and the last active admin
/// can never be deactivated or demoted. Deactivation revokes every session
/// (API tokens stop working too, because token lookup requires an active
/// user). Returns the updated user and a JSON summary of what changed.
pub fn admin_update(
    conn: &Connection,
    actor_id: &str,
    target_id: &str,
    req: &AdminUpdateUser,
) -> AppResult<(AdminUser, Value)> {
    let user = require(conn, target_id)?;
    let mut changes = Map::new();
    let is_self = actor_id == target_id;

    if req.is_active == Some(false) && is_self {
        return Err(AppError::bad_request(
            "you cannot deactivate your own account",
        ));
    }
    if req.is_admin == Some(false) && is_self {
        return Err(AppError::bad_request(
            "you cannot remove your own administrator role",
        ));
    }
    let loses_admin = user.is_admin
        && user.is_active
        && (req.is_active == Some(false) || req.is_admin == Some(false));
    if loses_admin && other_active_admins(conn, target_id)? == 0 {
        return Err(AppError::conflict(
            "cannot deactivate or demote the last active administrator",
        ));
    }

    let now = now_ms();
    if let Some(name) = &req.name {
        let name = validate_name(name)?;
        if name != user.name {
            conn.execute(
                "UPDATE users SET name = ?1, updated_at = ?2 WHERE id = ?3",
                params![name, now, target_id],
            )?;
            changes.insert("name".into(), json!(name));
        }
    }
    if let Some(active) = req.is_active {
        if active != user.is_active {
            conn.execute(
                "UPDATE users SET is_active = ?1, updated_at = ?2 WHERE id = ?3",
                params![active, now, target_id],
            )?;
            changes.insert("is_active".into(), json!(active));
        }
        if !active {
            session::delete_all_for_user(conn, target_id, None)?;
            // Connected apps end with the account's access: reactivating the account must not
            // bring an AI assistant back. (Personal access tokens are only suspended, as
            // documented in docs/security.md.)
            crate::store::oauth::revoke_all_for_user(conn, target_id)?;
        }
    }
    if let Some(admin) = req.is_admin {
        if admin != user.is_admin {
            conn.execute(
                "UPDATE users SET is_admin = ?1, updated_at = ?2 WHERE id = ?3",
                params![admin, now, target_id],
            )?;
            changes.insert("is_admin".into(), json!(admin));
        }
    }
    if req.disable_2fa && (user.totp_enabled || user.totp_secret.is_some()) {
        set_totp(conn, target_id, None, false)?;
        // A lost authenticator may mean a lost device: what was connected from it ends too.
        crate::store::oauth::revoke_all_for_user(conn, target_id)?;
        changes.insert("disable_2fa".into(), json!(true));
    }
    let updated = require(conn, target_id)?;
    Ok((admin_view(conn, &updated)?, Value::Object(changes)))
}

/// Create a single-use password-reset token for `user_id` valid for `ttl_ms`.
/// Returns the raw token (only its hash is stored) and its expiry.
pub fn create_reset_token(
    conn: &Connection,
    user_id: &str,
    ttl_ms: i64,
) -> AppResult<(String, i64)> {
    let token = new_token("rst_");
    let now = now_ms();
    let expires_at = now + ttl_ms;
    conn.execute(
        "INSERT INTO password_resets (token_hash, user_id, created_at, expires_at)
         VALUES (?1, ?2, ?3, ?4)",
        params![hash_token(&token), user_id, now, expires_at],
    )?;
    Ok((token, expires_at))
}

/// Link a user opens to choose a new password.
pub fn reset_url(public_url: &str, token: &str) -> String {
    format!(
        "{}/reset-password?token={token}",
        public_url.trim_end_matches('/')
    )
}

/// Redeem a reset token: if it is unused, unexpired and its user is active,
/// mark every outstanding reset token of that user used and return the user id.
pub fn consume_reset_token(conn: &Connection, token: &str) -> AppResult<Option<String>> {
    let now = now_ms();
    let user_id: Option<String> = conn
        .query_row(
            "SELECT r.user_id FROM password_resets r JOIN users u ON u.id = r.user_id
             WHERE r.token_hash = ?1 AND r.used_at IS NULL AND r.expires_at > ?2
               AND u.is_active = 1",
            params![hash_token(token), now],
            |r| r.get(0),
        )
        .optional()?;
    if let Some(uid) = &user_id {
        conn.execute(
            "UPDATE password_resets SET used_at = ?1 WHERE user_id = ?2 AND used_at IS NULL",
            params![now, uid],
        )?;
    }
    Ok(user_id)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn db() -> Connection {
        let c = Connection::open_in_memory().unwrap();
        c.execute_batch("PRAGMA foreign_keys = ON").unwrap();
        crate::db::migrate(&c).unwrap();
        c
    }

    #[test]
    fn email_validation() {
        assert_eq!(normalize_email("  a@b.co ").unwrap(), "a@b.co");
        assert!(normalize_email("nope").is_err());
        assert!(normalize_email("a@b").is_err());
        assert!(normalize_email("a b@c.com").is_err());
    }

    #[test]
    fn name_and_timezone_validation() {
        assert_eq!(validate_name("  Ann ").unwrap(), "Ann");
        assert!(validate_name("   ").is_err());
        assert!(validate_name(&"x".repeat(101)).is_err());
        assert!(validate_name("a\u{0}b").is_err());
        assert_eq!(
            validate_timezone("Europe/Berlin").unwrap().as_deref(),
            Some("Europe/Berlin")
        );
        assert_eq!(validate_timezone("").unwrap(), None);
        assert!(validate_timezone("Mars/Olympus").is_err());
    }

    #[test]
    fn duplicate_email_is_conflict_case_insensitively() {
        let c = db();
        create(&c, "a@example.com", "A", "!", false).unwrap();
        let err = create(&c, "A@Example.com", "A2", "!", false).unwrap_err();
        assert!(matches!(err, AppError::Conflict(_)));
        assert!(get_by_email(&c, "A@EXAMPLE.COM").unwrap().is_some());
    }

    #[test]
    fn last_active_admin_cannot_be_removed() {
        let c = db();
        let admin = create(&c, "a@example.com", "A", "!", true).unwrap();
        let other = create(&c, "b@example.com", "B", "!", false).unwrap();
        // Simulate a caller that is not the target (e.g. a future CLI path):
        let demote = AdminUpdateUser {
            is_admin: Some(false),
            ..Default::default()
        };
        let err = admin_update(&c, &other, &admin, &demote).unwrap_err();
        assert!(matches!(err, AppError::Conflict(_)), "{err:?}");
        let deactivate = AdminUpdateUser {
            is_active: Some(false),
            ..Default::default()
        };
        let err = admin_update(&c, &other, &admin, &deactivate).unwrap_err();
        assert!(matches!(err, AppError::Conflict(_)));
        // With a second active admin, it is allowed.
        admin_update(
            &c,
            &admin,
            &other,
            &AdminUpdateUser {
                is_admin: Some(true),
                ..Default::default()
            },
        )
        .unwrap();
        let (u, changes) = admin_update(&c, &other, &admin, &demote).unwrap();
        assert!(!u.is_admin);
        assert_eq!(changes, json!({"is_admin": false}));
    }

    #[test]
    fn inactive_admins_do_not_count_as_remaining_admins() {
        let c = db();
        let a = create(&c, "a@example.com", "A", "!", true).unwrap();
        let b = create(&c, "b@example.com", "B", "!", true).unwrap();
        c.execute("UPDATE users SET is_active = 0 WHERE id = ?1", [&b])
            .unwrap();
        let err = admin_update(
            &c,
            &b,
            &a,
            &AdminUpdateUser {
                is_active: Some(false),
                ..Default::default()
            },
        )
        .unwrap_err();
        assert!(matches!(err, AppError::Conflict(_)));
    }

    #[test]
    fn reset_tokens_are_single_use_and_expire() {
        let c = db();
        let u = create(&c, "a@example.com", "A", "!", false).unwrap();
        let (t1, _) = create_reset_token(&c, &u, RESET_TTL_MS).unwrap();
        let (t2, _) = create_reset_token(&c, &u, RESET_TTL_MS).unwrap();
        assert_eq!(
            consume_reset_token(&c, &t1).unwrap().as_deref(),
            Some(u.as_str())
        );
        assert_eq!(consume_reset_token(&c, &t1).unwrap(), None);
        // Redeeming one invalidates the user's other outstanding tokens.
        assert_eq!(consume_reset_token(&c, &t2).unwrap(), None);
        let (expired, _) = create_reset_token(&c, &u, -1).unwrap();
        assert_eq!(consume_reset_token(&c, &expired).unwrap(), None);
        assert_eq!(consume_reset_token(&c, "rst_bogus").unwrap(), None);
        // Inactive users cannot redeem.
        let (t3, _) = create_reset_token(&c, &u, RESET_TTL_MS).unwrap();
        c.execute("UPDATE users SET is_active = 0 WHERE id = ?1", [&u])
            .unwrap();
        assert_eq!(consume_reset_token(&c, &t3).unwrap(), None);
    }

    #[test]
    fn reset_url_shape() {
        assert_eq!(
            reset_url("https://g.example.com/", "rst_x"),
            "https://g.example.com/reset-password?token=rst_x"
        );
    }
}
